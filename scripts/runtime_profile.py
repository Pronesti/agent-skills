"""Detect local PHP command forms and install a machine-specific runtime profile."""
from pathlib import Path
import shutil
import stat

from atomic_files import write_atomic


def detect_runtime(runtime='auto'):
    executables = {}
    for name in ('lerd', 'yerd', 'php', 'composer'):
        command = shutil.which(name)
        if command:
            try:
                executables[name] = {'path': str(Path(command).absolute()),
                                     'resolved': str(Path(command).resolve(strict=True))}
            except (OSError, RuntimeError):
                continue
    result = {'selected': None, 'status': 'unavailable', 'executables': executables}
    has_direct = all(name in executables for name in ('php', 'composer'))
    php = executables.get('php', {}).get('resolved')
    composer = executables.get('composer', {}).get('resolved')
    yerd = executables.get('yerd', {}).get('resolved')
    yerd_shims = bool(has_direct and php == composer and
                      (php == yerd if yerd else Path(php).name == 'yerd'))
    has_yerd = 'yerd' in executables or any(
        Path(path).name == 'yerd' for path in (php, composer) if path
    )

    if runtime == 'lerd':
        if 'lerd' in executables:
            result.update(selected='lerd', status='detected', reason='Lerd explicitly selected and found on PATH.')
        else:
            result['reason'] = 'Lerd was selected but no executable lerd was found on PATH.'
    elif runtime == 'direct':
        if has_direct:
            result.update(selected='direct', status='detected', reason='Direct commands explicitly selected; php and composer found on PATH.')
        else:
            result['reason'] = 'Direct commands require both php and composer on PATH.'
    elif 'lerd' in executables and has_yerd:
        result.update(status='ambiguous', reason='Both Lerd and Yerd were found; select --runtime lerd or --runtime direct, or use --runtime skip.')
    elif 'lerd' in executables:
        result.update(selected='lerd', status='detected', reason='Lerd found on PATH without a competing Yerd installation.')
    elif yerd_shims:
        result.update(selected='direct', status='detected', reason='Both php and composer resolve to the Yerd launcher.')
    else:
        result['reason'] = 'No unambiguous Lerd or direct Yerd setup found. Check PATH, select --runtime lerd|direct, or use --runtime skip.'
    return result


def render_runtime(runtime):
    prefix = 'lerd ' if runtime == 'lerd' else ''
    mcp = ('\nWhen the lerd MCP server is connected, use its tools (such as `exec`) for PHP, Composer and\n'
           'framework console commands; these shell forms are the fallback.\n') if runtime == 'lerd' else ''
    return f"""# PHP and Composer runtime

Run PHP and Composer commands from the project directory:

- PHP: `{prefix}php ...`.
- Composer: `{prefix}composer ...`.

Honor the project's PHP version requirements. This profile selects command forms, not a PHP version.
{mcp}
Generated by agent-skills for this machine. After changing its runtime or PATH, preview
`python3 scripts/install.py --refresh-runtime` from the agent-skills checkout, then apply
with `./install.sh --refresh-runtime`. Existing profiles are otherwise preserved.
"""


def plan_runtime(home, runtime='auto', refresh=False):
    if runtime not in ('auto', 'lerd', 'direct', 'skip'):
        raise ValueError(f'Unknown runtime: {runtime}')
    if refresh and runtime == 'skip':
        raise ValueError('--refresh-runtime cannot be combined with --runtime skip')
    target = home / '.config/agent-skills/runtime.md'
    result = {'target': str(target), 'requested': runtime, 'refresh': refresh,
              'selected': None, 'status': 'skipped', 'content': None,
              'backup': None, 'executables': {}}
    if runtime == 'skip':
        return dict(result, reason='Runtime detection skipped explicitly.')
    if target.is_symlink():
        if refresh:
            raise RuntimeError(f'Runtime profile is a symlink at {target}; left untouched')
        return dict(result, status='preserved', reason='Existing runtime symlink preserved; no detection performed.')
    if target.exists():
        if not target.is_file():
            raise RuntimeError(f'Runtime profile at {target} is not a regular file; left untouched')
        if not refresh:
            return dict(result, status='preserved', reason='Existing runtime profile preserved; use --refresh-runtime to replace it with a backup.')
    result.update(detect_runtime(runtime))
    if result['selected']:
        result['content'] = render_runtime(result['selected'])
        result['status'] = ('unchanged' if target.exists() and
                            target.read_bytes() == result['content'].encode('utf-8') else 'planned')
    return result


def apply_runtime(plan, backup_root):
    if plan['status'] != 'planned':
        return plan
    result = dict(plan)
    target = Path(plan['target'])
    # Recheck after skill installation so a newly created profile is preserved too.
    exists = target.exists() or target.is_symlink()
    if exists and not plan['refresh']:
        return dict(result, status='preserved', content=None, reason='A runtime profile appeared during installation; preserved.')
    if target.is_symlink() or (exists and not target.is_file()):
        raise RuntimeError(f'Runtime profile at {target} must be a regular file; left untouched')
    content = plan['content'].encode('utf-8')
    if exists and target.read_bytes() == content:
        return dict(result, status='unchanged')
    mode = stat.S_IMODE(target.stat().st_mode) if exists else 0o644
    if exists:
        backup = backup_root / '.config/agent-skills/runtime.md'
        backup.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(target, backup)
        result['backup'] = str(backup)
    # An exclusive creation also protects a profile created after the recheck.
    if not write_atomic(target, content, mode, replace=exists):
        return dict(result, status='preserved', content=None, reason='A runtime profile appeared during installation; preserved.')
    result['status'] = 'written'
    return result
